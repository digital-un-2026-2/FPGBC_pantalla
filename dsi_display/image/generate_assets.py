"""Build reproducible fixed RGB888 packets and the sourced JDI initialization ROM."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COLORS = (0xffffff, 0xffff00, 0x00ffff, 0x00ff00, 0xff00ff, 0xff0000, 0x0000ff, 0)
SYNDROMES = (7, 11, 13, 14, 19, 21, 22, 25, 26, 28, 35, 37,
             38, 41, 42, 44, 49, 50, 52, 56, 31, 47, 55, 59)


def header(dt, data):
    raw = [dt, data & 255, data >> 8]
    value = int.from_bytes(bytes(raw), "little")
    ecc = 0
    for bit, syndrome in enumerate(SYNDROMES):
        if value & (1 << bit):
            ecc ^= syndrome
    return raw + [ecc]


def long_packet(dt, payload):
    crc = 0xffff
    for value in payload:
        for bit in range(8):
            crc = (crc >> 1) ^ (0x8408 if ((crc ^ (value >> bit)) & 1) else 0)
    return header(dt, len(payload)) + payload + [crc & 255, crc >> 8]


def generate():
    steps = json.loads((ROOT / "profiles/lt031mdz4000_init.json").read_text())["steps"]
    steps += json.loads((ROOT / "profiles/lt031mdz4000_backlight.json").read_text())["steps"]
    if len(steps) != 13:
        raise ValueError("La ROM espera 11 pasos JDI y 2 pasos opcionales de backlight")
    packets = []
    for step in steps:
        params = step["params"]
        if not params:
            packet = header(5, step["opcode"])
        elif len(params) == 1:
            packet = header(0x15, step["opcode"] | (params[0] << 8))
        else:
            packet = long_packet(0x39, [step["opcode"]] + params)
        if len(packet) > 15:
            raise ValueError("El motor de inicialización admite hasta 15 bytes")
        packets.append(packet)
    pixel_bytes = []
    for x in range(720):
        color = COLORS[x // 90]
        pixel_bytes.extend((color >> 16, (color >> 8) & 255, color & 255))
    sync = header(0x21, 0) + header(0x31, 0)
    eot = header(8, 0x0f0f)
    # Blank packets account for horizontal back/front porches around the RGB
    # burst. Front payload rounds up one byte to preserve two-lane alignment.
    back = long_packet(0x19, [0]*72)
    front = long_packet(0x19, [0]*64)
    active = sync + back + long_packet(0x3e, pixel_bytes) + front + eot
    blank = sync + back + long_packet(0x19, [0]*2160) + front + eot
    assert len(active) == len(blank) == 2326
    lines = ["`timescale 1ns/1ps", "// Generated by dsi_display/image/generate_assets.py; do not edit.",
             "// JDI register data provenance: profiles/lt031mdz4000_init.json.",
             "module display_image_rom (input clk, input [10:0] address, input active,",
             "  input [1:0] sync_kind, output reg [15:0] word,"
    ]
    lines += ["  input [3:0] init_index, init_position, output reg [7:0] init_byte,",
              "  output reg [3:0] init_length, output reg [7:0] init_delay_ms);",
              "  reg [15:0] rgb [0:1162];", "  reg [15:0] raw_word;",
              "  reg [10:0] address_q; reg active_q; reg [1:0] sync_q;", "  initial begin"]
    for n in range(0, len(active), 2):
        lines.append(f"    rgb[{n//2}]=16'h{active[n+1]:02x}{active[n]:02x};")
    lines += ["  end", "  always @(posedge clk) begin", "    raw_word<=rgb[address];",
              "    address_q<=address; active_q<=active; sync_q<=sync_kind;", "  end",
              "  always @(*) begin", "    word=raw_word;", "    if(!active_q) case(address_q)"]
    for n in range(0, len(blank), 2):
        if blank[n] or blank[n+1]:
            lines.append(f"      {n//2}: word=16'h{blank[n+1]:02x}{blank[n]:02x};")
    lines += ["      default: word=0;", "    endcase", "    if(address_q<2) case(sync_q)"]
    for kind, dt in enumerate((0x21, 0x01, 0x11)):
        h = header(dt, 0)
        lines.append(f"      2'd{kind}: word=address_q==0 ? 16'h{h[1]:02x}{h[0]:02x} : 16'h{h[3]:02x}{h[2]:02x};")
    lines += ["      default: word=0;", "    endcase", "  end", "  always @(*) begin",
              "    init_byte=0; init_length=0; init_delay_ms=0;", "    case(init_index)"]
    for n, packet in enumerate(packets):
        lines.append(f"      {n}: begin init_length=4'd{len(packet)}; init_delay_ms=8'd{steps[n]['delay_ms']}; end")
    lines += ["      default: begin end", "    endcase", "    case({init_index,init_position})"]
    for n, packet in enumerate(packets):
        for pos, value in enumerate(packet):
            lines.append(f"      8'h{n*16+pos:02x}: init_byte=8'h{value:02x};")
    lines += ["      default: init_byte=0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "dsi_display/src/display_image_rom.v"
    text = generate()
    if args.check:
        if path.read_text() != text:
            raise SystemExit("ROM desactualizada: regenerar los assets de imagen")
        print("PASS image assets match initialization and RGB888 source")
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
